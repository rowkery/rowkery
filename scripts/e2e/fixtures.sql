-- 40 columns × 200,000 rows: streaming, paging, scrolling, cancel.
CREATE TABLE e2e_big AS
SELECT g AS id,
       md5(g::text) AS c01, g * 2 AS c02, g * 3 AS c03, md5((g + 1)::text) AS c04,
       now() - g * interval '1 minute' AS c05, g % 2 = 0 AS c06, g::numeric / 7 AS c07,
       md5((g + 2)::text) AS c08, g % 100 AS c09, g % 1000 AS c10,
       md5((g + 3)::text) AS c11, g * 11 AS c12, g * 12 AS c13, md5((g + 4)::text) AS c14,
       g * 14 AS c15, g * 15 AS c16, md5((g + 5)::text) AS c17, g * 17 AS c18, g * 18 AS c19,
       md5((g + 6)::text) AS c20, g * 20 AS c21, g * 21 AS c22, md5((g + 7)::text) AS c23,
       g * 23 AS c24, g * 24 AS c25, md5((g + 8)::text) AS c26, g * 26 AS c27, g * 27 AS c28,
       md5((g + 9)::text) AS c29, g * 29 AS c30, g * 30 AS c31, md5((g + 10)::text) AS c32,
       g * 32 AS c33, g * 33 AS c34, md5((g + 11)::text) AS c35, g * 35 AS c36, g * 36 AS c37,
       md5((g + 12)::text) AS c38, g * 38 AS c39
FROM generate_series(1, 200000) AS g;
ALTER TABLE e2e_big ADD PRIMARY KEY (id);

CREATE VIEW e2e_active_people AS SELECT id, name, email FROM e2e_people WHERE active;
CREATE MATERIALIZED VIEW e2e_people_by_age AS SELECT age, count(*) AS n FROM e2e_people GROUP BY age;

CREATE TABLE e2e_events (id bigint, at date NOT NULL, kind text) PARTITION BY RANGE (at);
