-- The end-to-end database (scripts/e2e/run.mjs loads it into a fresh `rowkery_e2e`
-- after scripts/test-seed.sql): an editable table, one without a key,
-- a wide and long one, every kind of value the grid renders, a view, a
-- materialized view, a partitioned table, a sequence and comments.

CREATE TABLE e2e_people (
  id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  name text NOT NULL,
  email text,
  age integer,
  active boolean NOT NULL DEFAULT true,
  meta jsonb,
  balance numeric(12, 2),
  big bigint,
  born date,
  seen_at timestamptz DEFAULT now(),
  kiosk_id bigint REFERENCES kiosks (id)
);
COMMENT ON TABLE e2e_people IS 'People the end-to-end suites edit.';
COMMENT ON COLUMN e2e_people.email IS 'Null when unknown.';
